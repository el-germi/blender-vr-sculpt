_tris = {}


def _flatten(shapes):
    out = []
    for s in shapes:
        if isinstance(s, list):
            out += _flatten(s)
        else:
            out.append(s)
    return out


def _stroke(points, w):
    h = w / 2
    tris = []
    for (x0, y0), (x1, y1) in zip(points, points[1:]):
        dx, dy = x1 - x0, y1 - y0
        n = math.hypot(dx, dy)
        if n < 1e-9:
            continue
        px, py = -dy / n * h, dx / n * h
        a, b, c, d = (x0 + px, y0 + py), (x1 + px, y1 + py), (x1 - px, y1 - py), (x0 - px, y0 - py)
        tris += [a, b, c, a, c, d]
    for x, y in points:  # Round joints and caps.
        ring = [(x + h * math.cos(2 * math.pi * i / _JOINT), y + h * math.sin(2 * math.pi * i / _JOINT))
                for i in range(_JOINT)]
        for i in range(_JOINT):
            tris += [(x, y), ring[i], ring[(i + 1) % _JOINT]]
    return tris


def triangles(name, width=WIDTH):
    """Triangle corners (x, y) in the [-1, 1] box, or None for an unknown icon."""
    key = (name, width)
    if key in _tris:
        return _tris[key]
    shapes = ICONS.get(name)
    if shapes is None:
        _tris[key] = None
        return None
    tris = []
    for kind, pts in _flatten(shapes):
        if kind == 'L':
            tris += _stroke(pts, width)
        else:
            for i in range(1, len(pts) - 1):
                tris += [pts[0], pts[i], pts[i + 1]]
    _tris[key] = tris
    return tris


def exists(name):
    return ICONS.get(name) is not None


def draw(name, x, y, size, color, z=0.0, width=WIDTH):
    """Draw icon `name` centered at (x, y) in the current gpu matrix, `size` = half its width.
    False if there is no such icon."""
    tris = triangles(name, width)
    if not tris:
        return False
    shader = gpu.shader.from_builtin('UNIFORM_COLOR')
    pts = [(x + px * size, y + py * size, z) for px, py in tris]
    batch = batch_for_shader(shader, 'TRIS', {"pos": pts})
    shader.uniform_float("color", color)
    batch.draw(shader)
    return True
