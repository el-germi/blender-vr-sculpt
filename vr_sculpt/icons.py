"""Vector icons for the pies and the tip status: strokes and fills in a [-1, 1] box.

There are no image assets: each icon is a few polylines (drawn as thick lines with round joints)
and convex fills, tessellated once into triangles and cached. Unknown names draw nothing, and the
pie shows the slice's label instead.
"""

import math

