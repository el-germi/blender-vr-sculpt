WIDTH = 0.15  # stroke width, icon units
_JOINT = 6  # segments of the round joints


def _arc(cx, cy, r, a0=0.0, a1=360.0, n=None):
    n = n or max(int(abs(a1 - a0) / 15.0), 3)
    return [(cx + r * math.cos(math.radians(a0 + (a1 - a0) * i / n)),
             cy + r * math.sin(math.radians(a0 + (a1 - a0) * i / n))) for i in range(n + 1)]


def L(*pts):
    return ('L', list(pts))


def C(cx, cy, r, a0=0.0, a1=360.0):
    return ('L', _arc(cx, cy, r, a0, a1))


def R(x0, y0, x1, y1):
    return ('L', [(x0, y0), (x1, y0), (x1, y1), (x0, y1), (x0, y0)])


def F(*pts):
    return ('F', list(pts))


def D(cx, cy, r):
    return ('F', _arc(cx, cy, r, 0.0, 360.0, 16)[:-1])


def FR(x0, y0, x1, y1):
    return F((x0, y0), (x1, y0), (x1, y1), (x0, y1))


def _diamond(cx, cy, r, fill=False):
    pts = [(cx, cy + r), (cx + r, cy), (cx, cy - r), (cx - r, cy)]
    return F(*pts) if fill else L(*pts, pts[0])


def _arrow_head(x, y, angle, size=0.3):
    """A filled arrowhead with its tip at (x, y), pointing along angle (degrees)."""
    a = math.radians(angle)
    back = (x - size * math.cos(a), y - size * math.sin(a))
    side = (-math.sin(a) * size * 0.6, math.cos(a) * size * 0.6)
    return F((x, y), (back[0] + side[0], back[1] + side[1]), (back[0] - side[0], back[1] - side[1]))


def _curved_arrow(cx, cy, r, a0, a1):
    """An arc with an arrowhead at its a1 end."""
    end = (cx + r * math.cos(math.radians(a1)), cy + r * math.sin(math.radians(a1)))
    tangent = a1 + (90.0 if a1 > a0 else -90.0)
    return [C(cx, cy, r, a0, a1 - (12.0 if a1 > a0 else -12.0)), _arrow_head(end[0], end[1], tangent, 0.32)]


def _ellipse(cx, cy, rx, ry, a0=0.0, a1=360.0):
    return ('L', [(cx + rx * math.cos(math.radians(a0 + (a1 - a0) * i / 24)),
                   cy + ry * math.sin(math.radians(a0 + (a1 - a0) * i / 24))) for i in range(25)])


def _cube(s=0.62, dx=0.0, dy=0.0):
    a, b = 0.55 * s, 0.32 * s
    top = [(dx, dy + a + b), (dx + a, dy + a), (dx, dy + a - b), (dx - a, dy + a)]
    return [L(*top, top[0]), L((dx - a, dy + a), (dx - a, dy - a), (dx, dy - a - b), (dx + a, dy - a),
                              (dx + a, dy + a)), L((dx, dy + a - b), (dx, dy - a - b))]


def _bone(x0, y0, x1, y1, r=0.2):
    return [C(x0, y0, r), C(x1, y1, r * 0.75), L((x0 + r * 0.7, y0 + r * 0.7 * (1 if y1 > y0 else -1)),
                                                 (x1 - r * 0.5, y1 - r * 0.5 * (1 if y1 > y0 else -1)))]


def _wave(y, amp=0.25, x0=-0.8, x1=0.8, n=24, cycles=1.5):
    return L(*[(x0 + (x1 - x0) * i / n, y + amp * math.sin(2 * math.pi * cycles * i / n)) for i in range(n + 1)])


def _dots(points, r=0.11):
    return [D(x, y, r) for x, y in points]


